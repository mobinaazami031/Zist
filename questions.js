/* =========================================================
کپی امن سؤال
========================================================= */

function cloneQuestion(question) {

```
if (!question) {
    return null;
}

return JSON.parse(
    JSON.stringify(question)
);
```

}

/* =========================================================
مخلوط کردن آرایه
========================================================= */

function shuffleArray(array) {

```
const result = [...array];

for (
    let i = result.length - 1;
    i > 0;
    i--
) {

    const j =
        Math.floor(Math.random() * (i + 1));

    [
        result[i],
        result[j]
    ] = [
        result[j],
        result[i]
    ];
}

return result;
```

}

/* =========================================================
سؤال تصادفی
========================================================= */

function getShuffledQuestion(question) {

```
if (!question) {
    return null;
}

const copy =
    cloneQuestion(question);

if (
    Array.isArray(copy.options)
) {
    copy.options =
        shuffleArray(copy.options);
}

return copy;
```

}

/* =========================================================
گرفتن چند سؤال تصادفی
========================================================= */

function getRandomQuestions(
count = questions.length
) {

```
return shuffleArray(
    questions
)
    .slice(
        0,
        Math.max(0, count)
    )
    .map(cloneQuestion);
```

}

/* =========================================================
سؤال‌های یک مرحله
========================================================= */

function getQuestionsForStage(stageNumber) {

```
const stage =
    Number(stageNumber);

return questions
    .filter(question =>
        Number(question.stage) === stage
    )
    .map(cloneQuestion);
```

}

