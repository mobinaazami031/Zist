/*
 * پیدا کردن مأموریت یک مرحله
 */
function getMissionForStage(stageNumber) {
    return missions.find(function (mission) {
        return mission.stage === Number(stageNumber);
    }) || null;
}

/*
 * گرفتن عنوان مرحله
 */
function getMissionTitle(stageNumber) {
    const mission = getMissionForStage(stageNumber);

    if (!mission) {
        return "مرحله ناشناخته";
    }

    return mission.title;
}

/*
 * گرفتن توضیحات مرحله
 */
function getMissionDescription(stageNumber) {
    const mission = getMissionForStage(stageNumber);

    if (!mission) {
        return "";
    }

    return mission.description;
}

/*
 * گرفتن هدف مرحله
 */
function getMissionObjective(stageNumber) {
    const mission = getMissionForStage(stageNumber);

    if (!mission) {
        return "";
    }

    return mission.objective;
}

/*
 * گرفتن داستان مرحله
 */
function getMissionStory(stageNumber) {
    const mission = getMissionForStage(stageNumber);

    if (!mission) {
        return "";
    }

    return mission.story;
}

/*
 * گرفتن جایزه مرحله
 */
function getMissionReward(stageNumber) {
    const mission = getMissionForStage(stageNumber);

    if (!mission) {
        return 0;
    }

    return Number(mission.reward) || 0;
}
